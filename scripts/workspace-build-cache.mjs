import { createHash, randomUUID } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnPnpmSync } from "./pnpm-process.mjs";

const workspaceRoot = fileURLToPath(new URL("..", import.meta.url));
export const hostPackages = ["core", "renderer", "plugins", "runtime"];
const ignored = new Set(["node_modules", "dist", "tests", "test-results", "coverage"]);
const logical = file => file.replaceAll("\\", "/");

export function isDevelopmentInput(relative, generated = new Set()) {
  const file = logical(relative);
  return !file.split("/").some(part => ignored.has(part) || part.startsWith(".")) &&
    !/(?:^|\/)internal\/(?:vendor-generated|adapters-generated)(?:\/|$)/u.test(file) &&
    !/\.(?:test|spec)\.[cm]?[jt]sx?$/u.test(file) &&
    !file.endsWith(".tsbuildinfo") && !generated.has(file);
}

function generatedFiles(root) {
  try {
    return new Set(JSON.parse(readFileSync(path.join(root, "source-layout.json"), "utf8")).files.map(entry => entry.view));
  } catch (error) { if (error.code === "ENOENT") return new Set(); throw error; }
}

// Hash content and logical names, including absence. No mtime-only receipts:
// copied projects, branch switches and deleted outputs must be detected.
function hashPaths(root, paths, accept = () => true) {
  const hash = createHash("sha256");
  const add = value => { hash.update(String(Buffer.byteLength(value))).update(":").update(value); };
  function visit(file) {
    if (!accept(file)) return;
    const target = path.join(root, ...file.split("/"));
    let entries;
    try { entries = readdirSync(target, { withFileTypes: true }); }
    catch (error) {
      if (error.code === "ENOENT") return;
      if (error.code !== "ENOTDIR") throw error;
      let data = readFileSync(target);
      if (file === "package.json") {
        const pkg = JSON.parse(data.toString());
        delete pkg.agentUI; // Generated by build/prepack, not a build input.
        data = Buffer.from(JSON.stringify(pkg));
      }
      add(file); add(data);
      return;
    }
    for (const entry of entries.sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)) {
      visit(path.posix.join(file, entry.name));
    }
  }
  for (const file of paths) visit(file);
  return hash.digest("hex");
}

export function packageSourceFingerprint(root) {
  const generated = generatedFiles(root);
  return hashPaths(root, [""], file => isDevelopmentInput(file, generated));
}

function packageInputs(root, name) {
  const packageRoot = path.join(root, "packages", name);
  const generated = generatedFiles(packageRoot);
  // Package-local build/configuration files, including tsconfig*.json, plus
  // canonical source/assets. Keep tests, docs and intermediate views out.
  const files = readdirSync(packageRoot, { withFileTypes: true })
    .filter(entry => entry.isFile() && /\.(?:json|[cm]?[jt]s)$/u.test(entry.name))
    .map(entry => entry.name).sort();
  files.push("src", "scripts", "resources", "registry", "fixtures", "presets", "skills", "browser", "contracts", "operator", "THIRD_PARTY_NOTICES.md");
  const own = hashPaths(packageRoot, files, file => isDevelopmentInput(file, generated));
  const shared = ["pnpm-lock.yaml", "pnpm-workspace.yaml", "package.json", "tsconfig.json", ".npmrc", ".pnpmfile.cjs", "pnpmfile.cjs", "releases/compatibility.json",
    "scripts/clean-package-dist.mjs", "scripts/sync-package-release-metadata.mjs", "scripts/public-package-types.mjs", "scripts/pnpm-process.mjs",
    "scripts/workspace-build-cache.mjs", "node_modules/.agent-ui-platform.json"];
  if (name === "plugins") shared.push("scripts/plugin-presentation-usage.mjs", "scripts/finalize-esm-imports.mjs", "packages/creator/operator/src/project/generated-code-format.mjs");
  if (name === "creator") shared.push("artifacts/creator-documentation");
  return createHash("sha256").update(own).update(hashPaths(root, shared)).digest("hex");
}

/** The selected packages form a dependency graph, not a positional suffix. */
export function workspacePackageFingerprints(packages, { root = workspaceRoot } = {}) {
  const manifests = new Map(packages.map(name => [name, JSON.parse(readFileSync(path.join(root, "packages", name, "package.json"), "utf8"))]));
  const byName = new Map([...manifests].map(([name, pkg]) => [pkg.name, name]));
  const memo = new Map();
  const visiting = new Set();
  function fingerprint(name) {
    if (memo.has(name)) return memo.get(name);
    if (visiting.has(name)) throw new Error(`Cyclic development build dependency: ${name}`);
    visiting.add(name);
    const pkg = manifests.get(name);
    const deps = Object.keys({ ...pkg.dependencies, ...pkg.devDependencies, ...pkg.peerDependencies, ...pkg.optionalDependencies })
      .map(dependency => byName.get(dependency)).filter(Boolean).sort();
    const hash = createHash("sha256").update(packageInputs(root, name));
    for (const dep of deps) hash.update(dep).update(fingerprint(dep));
    visiting.delete(name);
    const value = hash.digest("hex");
    memo.set(name, value);
    return value;
  }
  return packages.map(fingerprint);
}

const receiptPath = (root, name) => path.join(root, "node_modules", ".cache", "agent-ui-build", `${name}.json`);
const outputPaths = name => name === "creator" ? ["dist", "operator/dist"] : ["dist"];
const requiredOutputs = name => name === "creator"
  ? ["dist/cli.js", "operator/dist/runtime/operator-runtime.mjs"]
  : ["dist/index.js"];
function outputFingerprint(root, name) {
  return hashPaths(path.join(root, "packages", name), outputPaths(name));
}

function buildPlan(packages, { root = workspaceRoot, force = false } = {}) {
  const inputs = workspacePackageFingerprints(packages, { root });
  return packages.flatMap((name, index) => {
    let receipt;
    try { receipt = JSON.parse(readFileSync(receiptPath(root, name), "utf8")); }
    catch (error) { if (error.code !== "ENOENT" && !(error instanceof SyntaxError)) throw error; }
    const input = inputs[index];
    const outputsExist = requiredOutputs(name).every(file => existsSync(path.join(root, "packages", name, ...file.split("/"))));
    const identity = { platform: process.platform, arch: process.arch, node: process.versions.node };
    if (!force && outputsExist && receipt?.input === input && JSON.stringify(receipt.identity) === JSON.stringify(identity) && receipt.output === outputFingerprint(root, name)) {
      console.log(`[Creator] Reusing ${name} build.`);
      return [];
    }
    return [{ name, input, identity }];
  });
}

function recordBuild(root, entry) {
  if (!requiredOutputs(entry.name).every(file => existsSync(path.join(root, "packages", entry.name, ...file.split("/"))))) {
    throw new Error(`Build output is incomplete: ${entry.name}`);
  }
  const file = receiptPath(root, entry.name);
  mkdirSync(path.dirname(file), { recursive: true });
  const temporary = `${file}.${randomUUID()}.tmp`;
  try {
    writeFileSync(temporary, JSON.stringify({ ...entry, output: outputFingerprint(root, entry.name) }) + "\n", { flag: "wx" });
    renameSync(temporary, file);
  } finally { rmSync(temporary, { force: true }); }
}

export function prepareWorkspacePackages(packages, { root = workspaceRoot, force = false, run = spawnPnpmSync } = {}) {
  const plan = buildPlan(packages, { root, force });
  for (const entry of plan) {
    // Invalidate before mutation; a failed/interrupted build is never reusable.
    rmSync(receiptPath(root, entry.name), { force: true });
    console.log(`[Creator] Building ${entry.name}...`);
    const result = run(["--filter", `@za38.03/agent-ui-${entry.name}`, "build"], { cwd: root, stdio: "inherit" });
    if (result.error) throw result.error;
    if (result.status !== 0) throw new Error(`Host package preparation failed: @za38.03/agent-ui-${entry.name}`);
    recordBuild(root, entry);
  }
  return plan.map(entry => entry.name);
}

/** Reuses the supervisor's tracked child processes and cancellation handling. */
export async function prepareWorkspacePackagesAsync(packages, build, { root = workspaceRoot } = {}) {
  const built = [];
  for (const entry of buildPlan(packages, { root })) {
    rmSync(receiptPath(root, entry.name), { force: true });
    if (!(await build(entry.name))) return built;
    recordBuild(root, entry);
    built.push(entry.name);
  }
  return built;
}
